async def update_if_version(
    session: AsyncSession, issue_id: uuid.UUID, version: int, **values: Any
) -> int | None:
    """Conditional update (plan R4): bumps ``version``; ``None`` when the version moved on
    (or the issue was deleted) since it was read."""
    context = require_org_context(session)
    return (
        await session.execute(
            update(Issue)
            .where(
                Issue.org_id == context.org_id,
                Issue.id == issue_id,
                Issue.version == version,
                Issue.deleted_at.is_(None),
            )
            .values(version=Issue.version + 1, updated_at=func.now(), **values)
            .returning(Issue.version)
        )
    ).scalar_one_or_none()


async def soft_delete(session: AsyncSession, issue_id: uuid.UUID, version: int) -> bool:
    return await update_if_version(session, issue_id, version, deleted_at=func.now()) is not None


async def set_rank(session: AsyncSession, issue_id: uuid.UUID, rank: str) -> bool:
    """Reorder only: rank is excluded from ``version`` (plan R4), so this never
    invalidates an open edit. Used by board/backlog moves (M9)."""
