IDEMPOTENCY_TTL = "24 hours"
# Core insert: the identity primary key is generated by the database (GENERATED ALWAYS).
ACTIVITY_TABLE = cast(Table, IssueActivity.__table__)
_BASE62 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
RANK_WIDTH = 6


def initial_rank(seq: int) -> str:
    """Interim rank (until M9's between-neighbours generator): the issue number in base-62
    over the ASCII-ordered alphabet, zero-padded to 6 digits, so new issues append in
    creation order under COLLATE "C". M9 keys use the same alphabet and column."""
    digits = []
    while seq:
        seq, remainder = divmod(seq, 62)
        digits.append(_BASE62[remainder])
    return "".join(reversed(digits)).rjust(RANK_WIDTH, "0")


