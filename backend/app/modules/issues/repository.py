async def allocate_seq(session: AsyncSession, project_id: uuid.UUID) -> int:
    """Next issue number. The counter row lock serializes creators per project until
    commit; a rollback returns the number (plan R4). Call last, right before the insert."""
    context = require_org_context(session)
    return int(
        (
            await session.execute(
                update(ProjectIssueCounter)
                .where(
                    ProjectIssueCounter.org_id == context.org_id,
                    ProjectIssueCounter.project_id == project_id,
                )
                .values(next_seq=ProjectIssueCounter.next_seq + 1)
                .returning(ProjectIssueCounter.next_seq)
            )
        ).scalar_one()
    )


