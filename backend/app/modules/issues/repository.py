# ----------------------------------------------------------------------------- issues
async def allocate_seq(session: AsyncSession, project_id: uuid.UUID) -> int:
    """Next issue number. The counter row lock serializes creators per project until
    commit; a rollback returns the number (plan R4). Call last, right before the insert."""
    context = require_org_context(session)
    return int(
        (
            await session.execute(
                update(ProjectIssueCounter)
                .where(
                    ProjectIssueCounter.org_id == context.org_id,
                    ProjectIssueCounter.project_id == project_id,
                )
                .values(next_seq=ProjectIssueCounter.next_seq + 1)
                .returning(ProjectIssueCounter.next_seq)
            )
        ).scalar_one()
    )


@dataclass(frozen=True, slots=True)
class NewIssue:
    id: uuid.UUID
    project: Project
    seq: int
    type_id: uuid.UUID
    status_id: uuid.UUID
    priority_id: uuid.UUID
    reporter_id: uuid.UUID
    summary: str
    description: str | None


async def insert_issue(session: AsyncSession, new: NewIssue) -> None:
    context = require_org_context(session)
    await session.execute(
        insert(Issue).values(
            id=new.id,
            org_id=context.org_id,
            project_id=new.project.id,
            workflow_id=new.project.workflow_id,
            seq=new.seq,
            type_id=new.type_id,
            status_id=new.status_id,
            priority_id=new.priority_id,
            reporter_id=new.reporter_id,
            summary=new.summary,
            description=new.description,
            rank=initial_rank(new.seq),
        )
    )


async def find_issue(session: AsyncSession, project_id: uuid.UUID, seq: int) -> Issue | None:
    """A live (not soft-deleted) issue; ``None`` also when RLS hides it."""
    context = require_org_context(session)
    return (
        await session.execute(
            select(Issue).where(
                Issue.org_id == context.org_id,
                Issue.project_id == project_id,
                Issue.seq == seq,
                Issue.deleted_at.is_(None),
            )
        )
    ).scalar_one_or_none()


async def update_if_version(
    session: AsyncSession, issue_id: uuid.UUID, version: int, **values: Any
) -> int | None:
    """Conditional update (plan R4): bumps ``version``; ``None`` when the version moved on
    (or the issue was deleted) since it was read."""
    context = require_org_context(session)
    return (
        await session.execute(
            update(Issue)
            .where(
                Issue.org_id == context.org_id,
                Issue.id == issue_id,
                Issue.version == version,
                Issue.deleted_at.is_(None),
            )
            .values(version=Issue.version + 1, updated_at=func.now(), **values)
            .returning(Issue.version)
        )
    ).scalar_one_or_none()


async def soft_delete(session: AsyncSession, issue_id: uuid.UUID, version: int) -> bool:
    return await update_if_version(session, issue_id, version, deleted_at=func.now()) is not None


async def set_rank(session: AsyncSession, issue_id: uuid.UUID, rank: str) -> bool:
    """Reorder only: rank is excluded from ``version`` (plan R4), so this never
    invalidates an open edit. Used by board/backlog moves (M9)."""
    context = require_org_context(session)
    result = await session.execute(
        update(Issue)
        .where(Issue.org_id == context.org_id, Issue.id == issue_id, Issue.deleted_at.is_(None))
        .values(rank=rank)
    )
    return bool(result.rowcount)  # type: ignore[attr-defined]


async def unassign_member(session: AsyncSession, user_id: uuid.UUID) -> list[uuid.UUID]:
    """Org-member removal effect (plan R4/M4): unassign every live issue of the member in
    the caller's transaction, bumping versions."""
    context = require_org_context(session)
    rows = await session.execute(
        update(Issue)
        .where(
            Issue.org_id == context.org_id,
            Issue.assignee_id == user_id,
            Issue.deleted_at.is_(None),
        )
        .values(assignee_id=None, version=Issue.version + 1, updated_at=func.now())
        .returning(Issue.id)
    )
    return list(rows.scalars())


async def add_activity(session: AsyncSession, entries: list[dict[str, Any]]) -> None:
    """Rows: ``issue_id``, ``action`` and optional ``field``/``old_value``/``new_value``.
    The actor is always the bound user (RLS enforces it)."""
    context = require_org_context(session)
    if entries:
        await session.execute(
            insert(ACTIVITY_TABLE).inline(),
            [
                {
                    "org_id": context.org_id,
                    "actor_id": context.user_id,
                    "field": None,
                    "old_value": None,
                    "new_value": None,
                    **entry,
                }
                for entry in entries
            ],
        )


async def list_activity(
    session: AsyncSession, issue_id: uuid.UUID, *, after_id: int | None, limit: int
) -> list[IssueActivity]:
    context = require_org_context(session)
    query = select(IssueActivity).where(
        IssueActivity.org_id == context.org_id, IssueActivity.issue_id == issue_id
    )
    if after_id is not None:
        query = query.where(IssueActivity.id > after_id)
    return list((await session.execute(query.order_by(IssueActivity.id).limit(limit))).scalars())


# ------------------------------------------------------------------------ issue views
@dataclass(frozen=True, slots=True)
class IssueFilter:
    project_id: uuid.UUID | None = None
    status_id: uuid.UUID | None = None
    status_category: str | None = None
    type_id: uuid.UUID | None = None
    priority_id: uuid.UUID | None = None
    assignee: uuid.UUID | None = None
    unassigned: bool = False
    updated_since: datetime | None = None


def _view_query() -> Any:
    return (
        select(
            Issue,
            Project.key.label("project_key"),
            WorkflowStatus.name.label("status_name"),
            WorkflowStatus.category.label("status_category"),
            IssueType.name.label("type_name"),
            IssueType.kind.label("type_kind"),
            Priority.name.label("priority_name"),
            Priority.color.label("priority_color"),
        )
        .join(Project, Project.id == Issue.project_id)
        .join(WorkflowStatus, WorkflowStatus.id == Issue.status_id)
        .join(IssueType, IssueType.id == Issue.type_id)
        .join(Priority, Priority.id == Issue.priority_id)
    )


async def issue_view(session: AsyncSession, issue_id: uuid.UUID) -> Any:
    context = require_org_context(session)
    return (
        await session.execute(
            _view_query().where(Issue.org_id == context.org_id, Issue.id == issue_id)
        )
    ).one()


async def list_issue_views(
    session: AsyncSession,
    filters: IssueFilter,
    *,
    all_projects: bool,
    sort: str,
    after: tuple[datetime, uuid.UUID] | None,
    limit: int,
) -> list[Any]:
    """One keyset-paginated query. Non-admins see only projects they belong to (checked
    here; RLS enforces the same rule)."""
    context = require_org_context(session)
    column = Issue.updated_at if sort.endswith("updated_at") else Issue.created_at
    descending = sort.startswith("-")
    conditions: list[ColumnElement[bool]] = [
        Issue.org_id == context.org_id,
        Issue.deleted_at.is_(None),
    ]
    if not all_projects:
        conditions.append(
            Issue.project_id.in_(
                select(ProjectMembership.project_id).where(
                    ProjectMembership.org_id == context.org_id,
                    ProjectMembership.user_id == func.app_current_user(),
                )
            )
        )
    if filters.project_id is not None:
        conditions.append(Issue.project_id == filters.project_id)
    if filters.status_id is not None:
        conditions.append(Issue.status_id == filters.status_id)
    if filters.status_category is not None:
        conditions.append(WorkflowStatus.category == filters.status_category)
    if filters.type_id is not None:
        conditions.append(Issue.type_id == filters.type_id)
    if filters.priority_id is not None:
        conditions.append(Issue.priority_id == filters.priority_id)
    if filters.unassigned:
        conditions.append(Issue.assignee_id.is_(None))
    elif filters.assignee is not None:
        conditions.append(Issue.assignee_id == filters.assignee)
    if filters.updated_since is not None:
        conditions.append(Issue.updated_at >= filters.updated_since)
    if after is not None:
        value, last_id = after
        if descending:
            conditions.append(or_(column < value, and_(column == value, Issue.id < last_id)))
        else:
            conditions.append(or_(column > value, and_(column == value, Issue.id > last_id)))
    order = (column.desc(), Issue.id.desc()) if descending else (column.asc(), Issue.id.asc())
    return list(
        await session.execute(_view_query().where(*conditions).order_by(*order).limit(limit))
    )


# ------------------------------------------------------------------- idempotency keys
async def claim_idempotency_key(session: AsyncSession, key: str, request_hash: bytes) -> bool:
    """First statement of an idempotent create (plan R4). A concurrent duplicate blocks
    on the primary key until the first transaction ends; an expired key is reclaimed.
    ``False``: a live key exists (read it with ``find_idempotency_key``)."""
    context = require_org_context(session)
    statement = pg_insert(IdempotencyKey).values(
        org_id=context.org_id,
        user_id=context.user_id,
        key=key,
        request_hash=request_hash,
        expires_at=func.now() + literal_column(f"interval '{IDEMPOTENCY_TTL}'"),
    )
    upsert = statement.on_conflict_do_update(
        index_elements=[IdempotencyKey.org_id, IdempotencyKey.user_id, IdempotencyKey.key],
        set_={
            "request_hash": statement.excluded.request_hash,
            "response_status": None,
            "response_body": None,
            "created_at": func.now(),
            "expires_at": statement.excluded.expires_at,
        },
        where=IdempotencyKey.expires_at <= func.now(),
    ).returning(IdempotencyKey.key)
    return (await session.execute(upsert)).scalar_one_or_none() is not None


async def find_idempotency_key(session: AsyncSession, key: str) -> IdempotencyKey | None:
    context = require_org_context(session)
    return (
        await session.execute(
            select(IdempotencyKey).where(
                IdempotencyKey.org_id == context.org_id,
                IdempotencyKey.user_id == func.app_current_user(),
                IdempotencyKey.key == key,
            )
        )
    ).scalar_one_or_none()


async def store_idempotent_response(
    session: AsyncSession, key: str, status: int, body: dict[str, Any]
) -> None:
    context = require_org_context(session)
    await session.execute(
        update(IdempotencyKey)
        .where(
            IdempotencyKey.org_id == context.org_id,
            IdempotencyKey.user_id == func.app_current_user(),
            IdempotencyKey.key == key,
        )
        .values(response_status=status, response_body=body)
    )
